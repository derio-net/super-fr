"""Shipped-lens lookup and a repo's effective lenses (spec 2026-11-12-review-lenses R1-R2).

Shipped lookup, the same walk `fr.verification.resolve` uses (`fr._shipped`):

    $FR_SHIPPED_LENSES_DIR/<id>.yaml           # explicit escape
    fr/lens_manifests/<id>.yaml                # inside the `fr` wheel
    ~/.claude/plugins/marketplaces/derio-net--super-fr/plugins/super-fr/lenses/<id>.yaml

`plugins/super-fr/lenses/` is canonical; the wheel copy is generated by
`scripts/sync-lenses-data.py` and guarded by `tests/unit/test_tripwire_shipped_lenses.py`.
"""

from __future__ import annotations

from pathlib import Path

from fr import _shipped
from fr.lenses.model import Lens, LensConfig, LensError, parse_config, parse_lens, read_text

REPO_CONFIG_REL = Path(".fr") / "lenses.yaml"
PLUGIN_LENSES_REL = Path("plugins") / "super-fr" / "lenses"
PACKAGED_LENSES_DIRNAME = "lens_manifests"
SHIPPED_ENV_VAR = "FR_SHIPPED_LENSES_DIR"


def shipped_lens_dir() -> Path | None:
    """The first existing directory of shipped lenses, or `None` when none is installed."""
    dirs = _shipped.shipped_dirs(
        env_var=SHIPPED_ENV_VAR,
        plugin_rel=PLUGIN_LENSES_REL,
        packaged=_shipped.packaged_dir(PACKAGED_LENSES_DIRNAME),
    )
    return next((d for d in dirs if d.is_dir() and any(d.glob("*.yaml"))), None)


def shipped_lenses() -> dict[str, Lens]:
    """The shipped lenses by id, `source == "shipped"`. Raises `LensError`.

    A manifest is named for its lens, as a shipped verification strategy is: a
    copy that kept another lens's id would otherwise replace that lens silently.
    """
    found = shipped_lens_dir()
    if found is None:
        # The wheel always carries them: none found is a broken install, and
        # reading it as "this repo has no lenses" would empty every lens set.
        raise LensError(
            "no shipped lens manifests were found (looked in $"
            f"{SHIPPED_ENV_VAR}, the fr package's {PACKAGED_LENSES_DIRNAME}/ and the "
            "installed plugin): reinstall fr"
        )
    out: dict[str, Lens] = {}
    for path in sorted(found.glob("*.yaml")):
        lens = parse_lens(read_text(path, str(path)), source=str(path))
        if lens.id != path.stem:
            raise LensError(f"{path}: the file is named {path.name} but its lens is {lens.id!r}")
        out[lens.id] = lens.model_copy(update={"source": "shipped"})
    return out


def load_config(root: Path) -> LensConfig:
    """`.fr/lenses.yaml` from the working tree; absent is an empty config. Raises `LensError`."""
    path = root / REPO_CONFIG_REL
    if not path.is_file():
        return LensConfig()
    source = str(REPO_CONFIG_REL)
    return parse_config(read_text(path, source), source=source)


def apply_config(shipped: dict[str, Lens], config: LensConfig) -> dict[str, Lens]:
    """Shipped lenses not disabled, replacements applied, plus the repo's own (R2)."""
    out = {k: v for k, v in shipped.items() if k not in config.disable}
    for lens_id, definition in config.lenses.items():
        source = "repo (replaces shipped)" if lens_id in shipped else "repo"
        out[lens_id] = Lens(
            id=lens_id, title=definition.title, brief=definition.brief, source=source
        )
    return out


def effective_lenses(root: Path) -> dict[str, Lens]:
    """The repo's effective lenses, keyed by id."""
    return apply_config(shipped_lenses(), load_config(root))


def review_lenses(root: Path, base_text: str | None, *, has_base: bool) -> dict[str, Lens]:
    """The lenses a feature is REVIEWED under (§3.A): the working tree's effective
    lenses, except that a lens effective on the default branch keeps the default
    branch's definition and cannot be disabled by the branch under review. A branch
    adds lenses for its own review; its change to an existing one takes effect once
    merged, as its removal of a path rule does. With no default branch (`has_base`
    false) the working tree is all there is."""
    head = effective_lenses(root)
    if not has_base:
        return head
    config = (
        parse_config(base_text, source="the default branch's .fr/lenses.yaml")
        if base_text
        else LensConfig()
    )
    return {**head, **apply_config(shipped_lenses(), config)}
