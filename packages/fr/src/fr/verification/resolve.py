"""Strategy resolution — repo > env > wheel > marketplace (spec §A, R1).

The same order as `fr.workflow.resolve` (its docstring owns the reasoning),
sharing one directory walk in `fr._shipped`:

    .fr/verifications/<name>.yaml                          # repo — wins wholesale
    $FR_SHIPPED_DEFAULTS_DIR/verifications/<name>.yaml     # explicit escape (R16)
    $FR_SHIPPED_VERIFICATIONS_DIR/<name>.yaml              # older escape, with a notice
    fr/defaults/verifications/<name>.yaml                  # inside the `fr` wheel
    ~/.claude/plugins/marketplaces/derio-net--super-fr/
        plugins/super-fr/defaults/verifications/<name>.yaml  # the plugin clone

`plugins/super-fr/defaults/verifications/` is canonical (spec
2026-11-19-event-driven-a-la-carte R15); the wheel copy is generated by
`scripts/sync-defaults-data.py` and guarded by
`tests/unit/test_tripwire_shipped_defaults.py`.
"""

from __future__ import annotations

from pathlib import Path

from fr import _shipped
from fr.artifacts.paths import KIND_DIRS
from fr.verification.model import RESERVED, StrategyError, StrategyManifest, parse_strategy

REPO_VERIFICATIONS_REL = Path(KIND_DIRS["verification"])
PLUGIN_VERIFICATIONS_REL = _shipped.plugin_rel("verifications")


def repo_verifications_dir(repo_root: Path) -> Path:
    """The repo's own strategies for the product checkout *repo_root*: `.fr/verifications/`
    in its configuration space, or the old `docs/superpowers/verifications/` while only
    that one exists (spec 2026-11-19-event-driven-a-la-carte R9, R13)."""
    from fr.config.space import located

    return located(Path(repo_root), "verification")


def packaged_shipped_verifications_dir() -> Path | None:
    """The shipped strategies inside the `fr` wheel, or `None` (no such data)."""
    return _shipped.packaged_kind_dir("verifications")


def shipped_verification_dirs(shipped_root: Path | None = None) -> list[Path]:
    """The shipped sources, in lookup order — one list for resolve AND list."""
    return _shipped.shipped_dirs(
        "verifications",
        packaged=packaged_shipped_verifications_dir(),
        shipped_root=shipped_root,
    )


def resolve_strategy(
    name: str, repo_root: Path | None, *, shipped_root: Path | None = None
) -> StrategyManifest:
    """Resolve strategy `name`; a repo file wins wholesale over a shipped one.

    `repo_root=None` searches only the shipped sources. Raises `StrategyError`
    naming EVERY searched path when none exists.
    """
    path, data = _resolved(name, repo_root, shipped_root=shipped_root)
    manifest = parse_strategy(data.decode(), source=str(path))
    if manifest.verification != name:
        raise StrategyError(
            f"{path}: manifest names itself {manifest.verification!r}, but its file is {name!r}"
        )
    return manifest


def resolved_strategy_path(
    name: str, repo_root: Path | None, *, shipped_root: Path | None = None
) -> Path:
    """The file `resolve_strategy` reads for `name` — or `StrategyError`
    naming every searched path."""
    if name == RESERVED:
        raise StrategyError(f"{RESERVED!r} is reserved: it means no strategy, it never resolves")

    shipped = shipped_verification_dirs(shipped_root)
    repo_dir = repo_verifications_dir(repo_root) if repo_root is not None else None
    candidates = (
        _shipped.lookup_candidates(name, repo_dir, shipped)
        if repo_dir is not None
        else [d / f"{name}.yaml" for d in shipped]
    )
    for path in candidates:
        if path.is_file() and _strategy_bytes(name, path, repo_root) is not None:
            return path

    searched = " and ".join(str(p) for p in candidates)
    raise StrategyError(f"unknown verification strategy {name!r} — searched {searched}")


def strategy_identity(
    name: str, repo_root: Path, *, shipped_root: Path | None = None
) -> tuple[str, str]:
    """`(source label, sha256)` of the manifest `name` resolves to — what a
    walk log records, so `deliver` can refuse a log walked on a manifest that
    has since changed (a repo strategy edited to rubber-stamp shows in the diff
    AND unbinds the log). `StrategyError` when it does not resolve."""
    import hashlib

    path, data = _resolved(name, repo_root, shipped_root=shipped_root)
    return _label(path.parent, repo_root), hashlib.sha256(data).hexdigest()


def _resolved(
    name: str, repo_root: Path | None, *, shipped_root: Path | None
) -> tuple[Path, bytes]:
    path = resolved_strategy_path(name, repo_root, shipped_root=shipped_root)
    data = _strategy_bytes(name, path, repo_root)
    assert data is not None  # resolved_strategy_path took only a usable candidate
    return path, data


def _strategy_bytes(name: str, path: Path, repo_root: Path | None) -> bytes | None:
    """*path*'s bytes; a repo strategy through `fr.config.degraded.usable_bytes`: its
    install and scenario argv are executable configuration (R7), so under quiet and stealth
    they come from the protected branch's reviewed tip, or None (the shipped strategy is
    used) while that branch is not protected (review p4-r3)."""
    if repo_root is None or path.parent != repo_verifications_dir(repo_root):
        return path.read_bytes()
    from fr.config.degraded import usable_bytes

    return usable_bytes(repo_root, path, f"use verification strategy {name!r}")


def _label(directory: Path, repo_root: Path) -> str:
    if directory == repo_verifications_dir(repo_root):
        return "repo"
    if directory == packaged_shipped_verifications_dir():
        return "wheel"
    if directory == Path.home() / _shipped.MARKETPLACE_ROOT / PLUGIN_VERIFICATIONS_REL:
        return "marketplace"
    return "env"


def list_strategies(repo_root: Path, *, shipped_root: Path | None = None) -> list[tuple[str, str]]:
    """`(name, source-label)` for every strategy that resolves, each name once.

    The label is where `resolve_strategy` would take it from: `repo`, `env`,
    `wheel` or `marketplace`.
    """
    shipped = shipped_verification_dirs(shipped_root)
    return [
        (name, _label(directory, repo_root))
        for name, directory in _shipped.listing(repo_verifications_dir(repo_root), shipped)
    ]
